<section class="risk-guide" aria-label="Risk level guide">
    <h3>Understanding risk levels</h3>
    <dl>
        <div><dt><span class="risk-key low" aria-hidden="true"></span>Low <span>1–30%</span></dt><dd>Lower screening concern; routine review.</dd></div>
        <div><dt><span class="risk-key medium" aria-hidden="true"></span>Medium <span>31–60%</span></dt><dd>Signs of distress; counselor follow-up may be needed.</dd></div>
        <div><dt><span class="risk-key high" aria-hidden="true"></span>High <span>61–85%</span></dt><dd>Elevated concern; prioritized counselor triage.</dd></div>
        <div><dt><span class="risk-key critical" aria-hidden="true"></span>Critical <span>86–100%</span></dt><dd>Urgent concern; immediate counselor and eligible guardian notification attempts.</dd></div>
    </dl>
    <p>These are system screening bands, not diagnoses or probabilities of harm. Counselor review determines the response. Bullying reports do not receive these risk levels.</p>
</section>
